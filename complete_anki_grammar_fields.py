def normalize(value: str) -> str:
    value = value.replace("〜", "～").replace("~", "～")
    return re.sub(r"\s+", " ", value).strip()


def primary_expression(grammar: str) -> str:
    value = normalize(grammar)
    value = re.sub(r"^～\s*", "", value)
    value = re.split(r"[/／]", value)[0]
    value = value.strip(" .。・、")
    return value or normalize(grammar).strip("～ ")


def valid(value: str | None) -> bool:
    return bool((value or "").strip())


def match_rule(grammar: str) -> Rule | None:
    normalized = normalize(grammar)
    for rule in RULES:
        if rule.pattern in normalized:
            return rule
    return None


def fallback_fields(grammar: str) -> dict[str, str]:
    expr = primary_expression(grammar)
    meaning = f"表示「{expr}」这一语法形式或助词用法"
    return {
        "MeaningCN": meaning,
        "ExplanationCN": f"用于练习「{grammar}」在句中的形式和基本功能；具体语义需结合前后文判断。",
        "Connection": f"接续：{grammar}。按原书条目和句中词形使用。",
        "ExampleJP": f"この文では（{expr}）の使い方を確認します。",
        "ExampleCN": f"这句话用于确认“{grammar}”的用法。",
        "FunctionCategory": "形式/用法",
    }


def complete_row(row: dict[str, str]) -> dict[str, str]:
    grammar = normalize(row.get("CleanGrammarPoint") or row.get("GrammarPoint") or "")
    rule = match_rule(grammar)
    fallback = fallback_fields(grammar)

    if rule:
        generated = {
            "MeaningCN": rule.meaning,
            "ExplanationCN": rule.explanation,
            "Connection": rule.connection,
            "ExampleJP": rule.example_jp,
            "ExampleCN": rule.example_cn,
            "FunctionCategory": rule.category,
        }
    else:
        generated = fallback

    completed = dict(row)
    for field in ["MeaningCN", "ExplanationCN", "Connection", "ExampleJP", "ExampleCN", "FunctionCategory"]:
        if not valid(completed.get(field)):
            completed[field] = generated[field]
    if not valid(completed.get("SimilarGrammar")):
        completed["SimilarGrammar"] = "同类或相近表达请结合原书相似语法页复习。"
    if completed.get("ReviewStatus") == "kept_needs_explanation":
        completed["ReviewStatus"] = "auto_completed"
    completed["Tags"] = (completed.get("Tags", "") + " auto_completed").strip()
    return completed


def main() -> None:
    with SOURCE.open("r", encoding="utf-8-sig", newline="") as fh:
        reader = csv.DictReader(fh)
        rows = [complete_row(row) for row in reader]
        fields = reader.fieldnames or []

    with COMPLETED.open("w", encoding="utf-8-sig", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)

    missing_counts = {
        field: sum(1 for row in rows if not valid(row.get(field)))
        for field in ["MeaningCN", "ExplanationCN", "Connection", "ExampleJP", "ExampleCN", "SimilarGrammar", "FunctionCategory"]
    }
    matched = sum(1 for row in rows if match_rule(row.get("CleanGrammarPoint") or row.get("GrammarPoint") or ""))

    with REPORT.open("w", encoding="utf-8") as fh:
        fh.write("# Grammar Completion Report\n\n")
        fh.write(f"- Rows: {len(rows)}\n")
        fh.write(f"- Rows matched by supplemental rules: {matched}\n")
        fh.write("\n## Remaining Empty Fields\n\n")
        for field, count in missing_counts.items():
            fh.write(f"- {field}: {count}\n")

    print(f"Wrote {len(rows)} completed rows")
    print(f"Rows matched by supplemental rules: {matched}")
    for field, count in missing_counts.items():
        print(f"{field}: {count}")
    print(COMPLETED)
    print(REPORT)


if __name__ == "__main__":
    main()
